def _tone(seconds=2, fmt="webm"):
    """A short sine tone generated by ffmpeg (opus/webm like Chrome records)."""
    with tempfile.TemporaryDirectory() as tmp:
        out = f"{tmp}/tone.{fmt}"
        codec = ["-c:a", "libopus"] if fmt == "webm" else []
        subprocess.run(
            [FFMPEG, "-hide_banner", "-loglevel", "error", "-f", "lavfi", "-i",
             f"sine=frequency=440:duration={seconds}", "-ac", "2", "-ar", "48000", *codec, out],
            check=True, timeout=60,
        )
        with open(out, "rb") as fh:
            return fh.read()


@override_settings(PROTECTED_MEDIA_ROOT=_MEDIA, USE_X_ACCEL_REDIRECT=False)
class ChatTestBase(TestCase):
    def setUp(self):
        cache.clear()
        self.a = _user("amina@example.test", first_name="Amina", last_name="Bello")
        self.b = _user("musa@example.test", first_name="Musa", last_name="Ali")
        self.c = _user("chidi@example.test", first_name="Chidi", last_name="Okeke")
        self.outsider = _user("out@example.test", first_name="Out")
        self.direct = start_thread(creator=self.a, participants=[self.b], initial_body="Hello Musa")
        self.group = start_thread(creator=self.a, participants=[self.b, self.c],
                                  subject="Team", initial_body="Hello team")
        self.first = self.direct.messages.get()

    def client_for(self, user):
        c = self.client_class()
        c.force_login(user)
        return c

    def updates(self, client, thread, **params):
        params.setdefault("after", 0)
        r = client.get(f"/messages/{thread.pk}/updates/", params)
        self.assertEqual(r.status_code, 200)
        return r.json()


