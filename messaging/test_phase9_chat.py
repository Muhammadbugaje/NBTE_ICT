class UpdatesEndpointTests(ChatTestBase):
    def test_new_messages_after_id_with_html_and_payload(self):
        cb = self.client_for(self.b)
        data = self.updates(cb, self.direct, after=0)
        self.assertEqual([m["id"] for m in data["new"]], [self.first.pk])
        self.assertIn('data-message-id="%d"' % self.first.pk, data["new"][0]["html"])
        payload = data["new"][0]["message"]
        self.assertEqual(payload["body"], "Hello Musa")
        self.assertFalse(payload["is_mine"])
        self.assertEqual(payload["sender"]["id"], self.a.pk)
        self.assertIn("server_time", data)
        again = self.updates(cb, self.direct, after=data["last_id"], since=data["server_time"])
        self.assertEqual(again["new"], [])

    def test_only_participants(self):
        r = self.client_for(self.outsider).get(f"/messages/{self.direct.pk}/updates/")
        self.assertEqual(r.status_code, 404)
        r = self.client_for(self.outsider).post(f"/messages/{self.direct.pk}/typing/")
        self.assertEqual(r.status_code, 404)

    def test_edited_and_deleted_messages_come_back_as_changed(self):
        cb = self.client_for(self.b)
        first = self.updates(cb, self.direct)
        since = first["server_time"]
        ca = self.client_for(self.a)
        ca.post(f"/messages/{self.direct.pk}/message/{self.first.pk}/edit/", {"body": "Edited hello"})
        data = self.updates(cb, self.direct, after=first["last_id"], since=since)
        self.assertEqual(len(data["changed"]), 1)
        self.assertEqual(data["changed"][0]["message"]["body"], "Edited hello")
        self.assertIsNotNone(data["changed"][0]["message"]["edited_at"])

        since = data["server_time"]
        ca.post(f"/messages/{self.direct.pk}/message/{self.first.pk}/delete/", {"scope": "everyone"})
        data = self.updates(cb, self.direct, after=first["last_id"], since=since)
        self.assertTrue(data["changed"][0]["message"]["is_deleted"])

    def test_reaction_changes_are_sent(self):
        cb = self.client_for(self.b)
        first = self.updates(cb, self.direct)
        self.client_for(self.a).post(
            f"/messages/{self.direct.pk}/message/{self.first.pk}/react/", {"emoji": "👍"},
            HTTP_X_REQUESTED_WITH="XMLHttpRequest")
        data = self.updates(cb, self.direct, after=first["last_id"], since=first["server_time"])
        reactions = data["changed"][0]["message"]["reactions"]
        self.assertEqual(reactions[0]["emoji"], "👍")
        self.assertEqual(reactions[0]["count"], 1)

    def test_receipts_for_my_messages(self):
        ca = self.client_for(self.a)
        data = self.updates(ca, self.direct)
        self.assertEqual(data["receipts"][str(self.first.pk)]["state"], "sent")
        self.updates(self.client_for(self.b), self.direct, visible="0")
        data = self.updates(ca, self.direct)
        self.assertEqual(data["receipts"][str(self.first.pk)]["state"], "delivered")
        self.updates(self.client_for(self.b), self.direct, visible="1")
        data = self.updates(ca, self.direct)
        self.assertEqual(data["receipts"][str(self.first.pk)]["state"], "read")

    def test_typing_users_are_reported_to_others_only(self):
        self.client_for(self.b).post(f"/messages/{self.direct.pk}/typing/")
        data = self.updates(self.client_for(self.a), self.direct)
        self.assertEqual([u["id"] for u in data["typing"]], [self.b.pk])
        self.assertEqual(data["typing"][0]["first_name"], "Musa")
        self.assertEqual(self.updates(self.client_for(self.b), self.direct)["typing"], [])
        # Sending a message clears the indicator.
