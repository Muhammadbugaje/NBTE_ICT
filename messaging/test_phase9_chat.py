class ForwardTests(ChatTestBase):
    def test_forward_copies_text_and_file_bytes(self):
        msg = chat_services.send_message(
            self.direct, self.a, body="See attached",
            uploads=[SimpleUploadedFile("report.pdf", b"%PDF-1.4 hello", content_type="application/pdf")])
        r = self.client_for(self.a).post(
            f"/messages/{self.direct.pk}/message/{msg.pk}/forward/",
            {"threads": [self.group.pk]}, HTTP_X_REQUESTED_WITH="XMLHttpRequest")
        self.assertTrue(r.json()["ok"])
        copy = self.group.messages.latest("id")
        self.assertTrue(copy.forwarded)
        self.assertEqual(copy.body, "See attached")
        src = msg.attachments.get()
        dst = copy.attachments.get()
        self.assertNotEqual(src.file.name, dst.file.name)
        self.assertEqual(dst.original_name, "report.pdf")
        with dst.file.open("rb") as fh:
            self.assertEqual(fh.read(), b"%PDF-1.4 hello")
        # Deleting the original's file leaves the copy intact.
        src.hard_delete()
        self.assertTrue(dst.file.storage.exists(dst.file.name))
        self.assertIn("Forwarded", self.client_for(self.b).get(f"/messages/{self.group.pk}/").content.decode())

    def test_forward_only_to_my_threads(self):
        foreign = start_thread(creator=self.c, participants=[self.outsider], initial_body="private")
        r = self.client_for(self.a).post(
            f"/messages/{self.direct.pk}/message/{self.first.pk}/forward/",
            {"threads": [self.group.pk, foreign.pk]}, HTTP_X_REQUESTED_WITH="XMLHttpRequest")
        self.assertEqual(r.status_code, 400)
        self.assertEqual(foreign.messages.count(), 1)
        self.assertEqual(self.group.messages.count(), 1)


