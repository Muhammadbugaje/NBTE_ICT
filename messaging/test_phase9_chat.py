class PollTests(ChatTestBase):
    def make_poll(self, multiple=False):
        msg = chat_services.create_poll(self.group, self.a, question="Lunch?",
                                        options=["Rice", "Beans", "Yam"], allow_multiple=multiple)
        return ChatPoll.objects.get(message=msg)

    def test_polls_only_in_groups_and_validated(self):
        with self.assertRaises(Exception):
            chat_services.create_poll(self.direct, self.a, question="Q", options=["a", "b"])
        with self.assertRaises(Exception):
            chat_services.create_poll(self.group, self.a, question="Q", options=["only one"])
        with self.assertRaises(Exception):
            chat_services.create_poll(self.group, self.a, question="Q", options=list("abcdefg"))

    def test_single_choice_replaces(self):
        poll = self.make_poll()
        rice, beans, _ = poll.options.all()
        chat_services.vote_poll(poll, self.b, [rice.pk])
        chat_services.vote_poll(poll, self.b, [beans.pk])
        self.assertEqual(list(poll.votes.filter(user=self.b).values_list("option_id", flat=True)), [beans.pk])
        with self.assertRaises(Exception):
            chat_services.vote_poll(poll, self.b, [rice.pk, beans.pk])
        chat_services.vote_poll(poll, self.c, [beans.pk])
        res = chat_services.poll_results(poll, self.b)
        self.assertEqual(res["voter_count"], 2)
        beans_row = next(o for o in res["options"] if o["id"] == beans.pk)
        self.assertEqual((beans_row["votes"], beans_row["percent"], beans_row["mine"]), (2, 100, True))

    def test_multiple_choice(self):
        poll = self.make_poll(multiple=True)
        rice, beans, yam = poll.options.all()
        chat_services.vote_poll(poll, self.b, [rice.pk, yam.pk])
        chat_services.vote_poll(poll, self.c, [rice.pk])
        res = chat_services.poll_results(poll, self.a)
        counts = {o["id"]: (o["votes"], o["percent"]) for o in res["options"]}
        self.assertEqual(counts[rice.pk], (2, 100))
        self.assertEqual(counts[yam.pk], (1, 50))
        self.assertEqual(counts[beans.pk], (0, 0))
        chat_services.vote_poll(poll, self.b, [beans.pk])
        self.assertEqual(set(poll.votes.filter(user=self.b).values_list("option_id", flat=True)), {beans.pk})

    def test_endpoints_and_live_update(self):
        r = self.client_for(self.a).post(
            f"/messages/{self.group.pk}/poll/",
            {"question": "Meeting day?", "options": ["Mon", "Tue"], "allow_multiple": ""},
            HTTP_X_REQUESTED_WITH="XMLHttpRequest")
        self.assertTrue(r.json()["ok"])
        self.assertEqual(r.json()["message"]["kind"], "poll")
