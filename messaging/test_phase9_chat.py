class ReceiptTests(ChatTestBase):
    def test_direct_delivered_then_read(self):
        participants = chat_services.thread_participants(self.direct)
        self.assertEqual(chat_services.receipt_for(self.first, participants)["state"], "sent")
        p = self.direct.participants.get(user=self.b)
        chat_services.mark_delivered(p)
        participants = chat_services.thread_participants(self.direct)
        self.assertEqual(chat_services.receipt_for(self.first, participants)["state"], "delivered")
        chat_services.mark_read(self.direct, self.b)
        msg = Message.objects.get(pk=self.first.pk)
        r = chat_services.receipt_for(msg, chat_services.thread_participants(self.direct))
        self.assertEqual((r["state"], r["read_by"], r["total"]), ("read", 1, 1))

    def test_opening_thread_marks_delivered(self):
        self.client_for(self.b).get(f"/messages/{self.direct.pk}/")
        self.assertIsNotNone(self.direct.participants.get(user=self.b).last_delivered_at)

    def test_group_counts_and_info(self):
        msg = self.group.messages.get()
        chat_services.mark_read(self.group, self.b)
        r = chat_services.receipt_for(msg, chat_services.thread_participants(self.group))
        self.assertEqual((r["state"], r["read_by"], r["delivered_to"], r["total"]), ("sent", 1, 1, 2))
        self.assertEqual(chat_services.receipt_label(r, True), "Sent · read by 1 of 2")
        chat_services.mark_delivered(self.group.participants.get(user=self.c))
        r = chat_services.receipt_for(msg, chat_services.thread_participants(self.group))
        self.assertEqual(r["state"], "delivered")
        info = chat_services.message_info(Message.objects.get(pk=msg.pk), self.a)
        self.assertEqual([x["name"] for x in info["read"]], ["Musa Ali"])
        self.assertEqual([x["name"] for x in info["delivered"]], ["Chidi Okeke"])
        r = self.client_for(self.a).get(f"/messages/{self.group.pk}/message/{msg.pk}/info/",
                                        HTTP_ACCEPT="application/json")
        self.assertEqual(r.status_code, 200)
        self.assertIn("Musa Ali", r.json()["html"])
        self.assertEqual(r.json()["receipt"]["read_by"], 1)
        r = self.client_for(self.outsider).get(f"/messages/{self.group.pk}/message/{msg.pk}/info/")
        self.assertEqual(r.status_code, 404)

    def test_group_tooltip_in_html(self):
        chat_services.mark_read(self.group, self.b)
        chat_services.mark_read(self.group, self.c)
        r = self.client_for(self.a).get(f"/messages/{self.group.pk}/")
        self.assertContains(r, "Read by 2 of 2")
        self.assertContains(r, "msg-ticks is-read")


