@skipUnless(HAS_FFMPEG, "ffmpeg is required for voice-note tests")
@override_settings(VOICE_TRANSCRIBE_BACKEND="dummy")
class VoiceNoteTests(ChatTestBase):
    def upload(self, user, data, name="voice-note.webm", ctype="audio/webm", thread=None):
        thread = thread or self.direct
        f = SimpleUploadedFile(name, data, content_type=ctype)
        with self.captureOnCommitCallbacks(execute=True):
            return self.client_for(user).post(
                f"/messages/{thread.pk}/voice/", {"audio": f, "duration_ms": "2000"},
                HTTP_X_REQUESTED_WITH="XMLHttpRequest")

    def test_upload_normalises_to_aac_mono_16k(self):
        r = self.upload(self.a, _tone(2))
        self.assertEqual(r.status_code, 200, r.content)
        body = r.json()
        self.assertEqual(body["message"]["kind"], "voice")
        vn = VoiceNote.objects.get(message_id=body["message_id"])
        self.assertEqual(vn.mime, "audio/mp4")
        self.assertTrue(vn.file.name.endswith(".m4a"))
        self.assertEqual(len(vn.waveform), 48)
        self.assertTrue(all(0 <= v <= 100 for v in vn.waveform))
        self.assertEqual(max(vn.waveform), 100)
        self.assertAlmostEqual(vn.duration_ms, 2000, delta=250)
        self.assertEqual(vn.size_bytes, vn.file.size)
        self.assertLess(vn.size_bytes, 20000)  # ~24 kbit/s
        if FFPROBE:
            out = subprocess.run(
                [FFPROBE, "-v", "error", "-show_entries", "stream=codec_name,channels,sample_rate,profile",
                 "-of", "json", vn.file.path], capture_output=True, check=True, timeout=30).stdout
            stream = json.loads(out)["streams"][0]
            self.assertEqual(stream["codec_name"], "aac")
            self.assertEqual(stream["channels"], 1)
            self.assertEqual(stream["sample_rate"], "16000")
            self.assertEqual(stream["profile"], "LC")
        # Dummy transcription ran after commit.
        vn.refresh_from_db()
        self.assertEqual(vn.transcript_status, VoiceNote.DONE)
        self.assertIn("Dummy transcript", vn.transcript)
        self.assertEqual(vn.transcript_language, "en")
        self.assertIsNotNone(vn.transcribed_at)

    def test_wav_upload_also_works(self):
        r = self.upload(self.a, _tone(1, "wav"), name="note.wav", ctype="audio/wav")
        self.assertEqual(r.status_code, 200, r.content)

    def test_size_limit_and_wrong_type(self):
        big = b"\x1a\x45\xdf\xa3" + b"0" * (voice.MAX_VOICE_BYTES + 1)
        r = self.upload(self.a, big)
        self.assertEqual(r.status_code, 400)
        self.assertIn("20 MB", r.json()["error"])
        r = self.upload(self.a, b"just some text, not audio at all" * 4, name="x.txt", ctype="text/plain")
        self.assertEqual(r.status_code, 400)
        r = self.upload(self.a, b"just some text, not audio at all" * 4, name="x.webm", ctype="audio/webm")
        self.assertEqual(r.status_code, 400)
        self.assertFalse(VoiceNote.objects.exists())

    def test_only_participants_can_download_and_range_works(self):
        r = self.upload(self.a, _tone(2))
        vn = VoiceNote.objects.get(message_id=r.json()["message_id"])
        self.assertEqual(self.client_for(self.outsider).get(f"/messages/voice/{vn.pk}/audio/").status_code, 404)
        self.assertFalse(vn.can_download(self.outsider))
        cb = self.client_for(self.b)
        full = cb.get(f"/messages/voice/{vn.pk}/audio/")
        self.assertEqual(full.status_code, 200)
        self.assertEqual(full["Content-Type"], "audio/mp4")
        part = cb.get(f"/messages/voice/{vn.pk}/audio/", HTTP_RANGE="bytes=0-99")
        self.assertEqual(part.status_code, 206)
        self.assertEqual(len(part.content), 100)
        self.assertTrue(part["Content-Range"].startswith("bytes 0-99/"))
        # Deleted for me -> gone for me only.
        chat_services.delete_message(vn.message, self.b, "me")
        self.assertEqual(cb.get(f"/messages/voice/{vn.pk}/audio/").status_code, 404)
        self.assertEqual(self.client_for(self.a).get(f"/messages/voice/{vn.pk}/audio/").status_code, 200)

    def test_played_marker(self):
        r = self.upload(self.a, _tone(1))
        vn = VoiceNote.objects.get(message_id=r.json()["message_id"])
        payload = chat_services.message_payload(Message.objects.get(pk=vn.message_id), self.b)
        self.assertFalse(payload["voice_note"]["played"])
        self.client_for(self.b).post(f"/messages/voice/{vn.pk}/played/")
        payload = chat_services.message_payload(Message.objects.get(pk=vn.message_id), self.b)
        self.assertTrue(payload["voice_note"]["played"])

    @override_settings(VOICE_TRANSCRIBE_BACKEND="none")
    def test_backend_none_marks_unavailable(self):
        r = self.upload(self.a, _tone(1))
        vn = VoiceNote.objects.get(message_id=r.json()["message_id"])
        self.assertEqual(vn.transcript_status, VoiceNote.UNAVAILABLE)
        page = self.client_for(self.b).get(f"/messages/{self.direct.pk}/")
        self.assertContains(page, "Transcript unavailable")

    def test_transcript_edit_only_by_sender(self):
        r = self.upload(self.a, _tone(1))
        vn = VoiceNote.objects.get(message_id=r.json()["message_id"])
        r = self.client_for(self.b).post(f"/messages/voice/{vn.pk}/transcript/",
                                         {"transcript": "hijack"}, HTTP_X_REQUESTED_WITH="XMLHttpRequest")
        self.assertEqual(r.status_code, 403)
        r = self.client_for(self.a).post(f"/messages/voice/{vn.pk}/transcript/",
                                         {"transcript": "Corrected words"},
                                         HTTP_X_REQUESTED_WITH="XMLHttpRequest")
        self.assertTrue(r.json()["ok"])
        vn.refresh_from_db()
        self.assertEqual(vn.transcript, "Corrected words")
        self.assertTrue(vn.transcript_edited)
        # A late automatic run never overwrites the sender's correction.
        transcription.transcribe(vn)
        vn.refresh_from_db()
        self.assertEqual(vn.transcript, "Corrected words")

    def test_forward_voice_note_copies_audio(self):
        r = self.upload(self.a, _tone(1))
        vn = VoiceNote.objects.get(message_id=r.json()["message_id"])
        [copy] = chat_services.forward_message(vn.message, self.a, [self.group.pk])
        copy_vn = VoiceNote.objects.get(message=copy)
        self.assertNotEqual(copy_vn.file.name, vn.file.name)
        self.assertEqual(copy_vn.size_bytes, vn.size_bytes)

    def test_delete_for_everyone_removes_audio(self):
        r = self.upload(self.a, _tone(1))
        vn = VoiceNote.objects.get(message_id=r.json()["message_id"])
        path = vn.file.name
        storage = vn.file.storage
        chat_services.delete_message(vn.message, self.a, "everyone")
        self.assertFalse(VoiceNote.all_objects.filter(pk=vn.pk).exists())
        self.assertFalse(storage.exists(path))


