class PinMuteFilterTests(ChatTestBase):
    def test_pin_limit(self):
        threads = [start_thread(creator=self.a, participants=[self.c], subject=f"T{i}",
                                initial_body="x") for i in range(6)]
        for t in threads[:5]:
            chat_services.set_pinned(t.participants.get(user=self.a), True)
        with self.assertRaises(Exception):
            chat_services.set_pinned(threads[5].participants.get(user=self.a), True)
        r = self.client_for(self.a).post(f"/messages/{threads[5].pk}/pin/", {"pinned": "1"},
                                         HTTP_X_REQUESTED_WITH="XMLHttpRequest")
        self.assertEqual(r.status_code, 400)
        self.assertIn("up to 5", r.json()["error"])
        listed = chat_services.inbox_threads(self.a)
        self.assertTrue(all(t.is_pinned for t in listed[:5]))
        self.assertFalse(listed[5].is_pinned)

    def test_pinned_on_top_in_inbox(self):
        self.client_for(self.a).post(f"/messages/{self.direct.pk}/pin/", {"pinned": "1"})
        r = self.client_for(self.a).get("/messages/")
        self.assertContains(r, 'data-section="pinned"')
        html = r.content.decode()
        self.assertLess(html.index(f'data-thread-id="{self.direct.pk}"'),
                        html.index(f'data-thread-id="{self.group.pk}"'))

    def test_mute_suppresses_notifications_but_counts_unread(self):
        p = self.direct.participants.get(user=self.b)
        chat_services.set_muted(p, "8h")
        before = Notification.objects.filter(recipient=self.b).count()
        chat_services.send_message(self.direct, self.a, body="Muted one")
        self.assertEqual(Notification.objects.filter(recipient=self.b).count(), before)
        self.assertEqual(self.direct.unread_count_for(self.b), 2)
        chat_services.set_muted(p, "off")
        chat_services.send_message(self.direct, self.a, body="Loud one")
        self.assertEqual(Notification.objects.filter(recipient=self.b).count(), before + 1)

    def test_mute_options(self):
        p = self.direct.participants.get(user=self.b)
        chat_services.set_muted(p, "always")
        self.assertGreater(p.muted_until.year, 2900)
        chat_services.set_muted(p, "1w")
        self.assertAlmostEqual((p.muted_until - timezone.now()).days, 6, delta=1)
        r = self.client_for(self.b).post(f"/messages/{self.direct.pk}/mute/", {"duration": "bogus"},
                                         HTTP_X_REQUESTED_WITH="XMLHttpRequest")
        self.assertEqual(r.status_code, 400)

    def test_filters(self):
        kinds = {k: [t.pk for t in chat_services.inbox_threads(self.b, kind=k)]
                 for k in ("all", "groups", "direct", "unread")}
        self.assertEqual(set(kinds["all"]), {self.direct.pk, self.group.pk})
        self.assertEqual(kinds["groups"], [self.group.pk])
        self.assertEqual(kinds["direct"], [self.direct.pk])
        chat_services.mark_read(self.direct, self.b)
        self.assertEqual([t.pk for t in chat_services.inbox_threads(self.b, kind="unread")],
                         [self.group.pk])
        r = self.client_for(self.b).get("/messages/?filter=groups")
        self.assertContains(r, 'data-kind="groups"')
        self.assertContains(r, 'data-inbox-kind="groups"')
        self.assertContains(r, 'data-thread-kind="group"')


