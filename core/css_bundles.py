"""CSS consolidation (v2.1 Phase A, V7 / T-UX-2).

The design-system stylesheets that every page loads are concatenated into a
few bundle files in static/css/ (same folder, so relative url()s keep
working and ManifestStaticFilesStorage can hash them). The shared design
system is wrapped in cascade layers:

    @layer tokens, base, components, motion, pages;

  tokens      tokens.css (semantic tokens, palettes, density)
  base        base.css, layout.css
  components  components.css, utilities.css, animations.css, ux.css,
              components-buttons.css (X52 button spacing), then (bundle
              "app") the shared module styles of the internal shell
  motion      motion.css (motion kit + hero scenes)
  pages       brand.css (logo slots, hero crest, history); the per-page files and
              the Phase 6/7 design layer (apple, polish, qa-redesign) stay
              UNLAYERED so they keep beating the shared layers exactly as
              they did when they were linked after them.

Bundles are built by `python manage.py build_css` and checked by
`core/test_v7_css_bundles.py` (a stale bundle fails the test). Setting
`ui.legacy_css = true` makes {% css_bundle %} print the original files one
by one again (fallback for one release).
"""
from pathlib import Path

from django.conf import settings

CSS_DIR = Path(settings.BASE_DIR) / "static" / "css"
LAYER_ORDER = ("tokens", "base", "components", "motion", "pages")

# name -> list of (layer or None, [files]); files are relative to static/css.
# A file listed with a trailing "?" is optional (skipped when missing).
BUNDLES = {
    # Every page (templates/partials/head.html)
    "core": [
        ("tokens", ["tokens.css"]),
        ("base", ["base.css", "layout.css"]),
        ("components", ["components.css", "utilities.css", "animations.css", "ux.css",
                        "components-buttons.css"]),   # X52 .btn-group + safety net (pa-brand)
        ("motion", ["motion.css"]),
        ("pages", ["brand.css"]),                     # logo slots, hero crest, history (pa-brand)
        (None, ["nbte-loader.css"]),                  # crest loader, spinners, busy buttons, add-to-calendar (unlayered)
    ],
    # Internal shell (templates/base.html): shared module styles
    "app": [
        ("components", ["app-shell.css", "notifications.css", "workflow.css", "holidays.css", "users.css",
                        "messaging.css", "memo.css", "search.css", "staff-avatar.css"]),
    ],
    # QA portal shell (templates/qa_portal/base_portal.html)
    "portal": [
        (None, ["qa.css", "qa-portal.css", "qa-p2.css", "qa-p3.css", "qa-p5.css", "qa-records.css", "qa-p8.css",
                "complaints.css", "qa-pr.css", "ux-journey.css"]),
    ],
    # Phase 6/7 design layer, loaded last (base.html, base_portal.html)
    # (+ v21-platform.css: profile tabs and platform banners, which used to
    # link it from the page body, i.e. after everything else)
    "finish": [(None, ["apple.css", "polish.css", "qa-redesign.css", "v21-platform.css", "nbte-ux.css", "ux-pages.css",
                                    "ux-finance.css", "ux-portal.css", "ux-appdetail.css", "ux-case.css",
                                    "work-hub.css"])],   # Requests / Tasks / Tickets heroes + polish
    # Same for the public and sign-in shells (no qa-redesign)
    "finish-public": [(None, ["apple.css", "polish.css", "nbte-ux.css"])],
    # QA portal sign-in shell (templates/qa_portal/base_auth.html)
    "portal-auth": [(None, ["auth.css", "qa.css", "qa-portal.css", "qa-p2.css", "nbte-ux.css", "ux-portal.css"])],
    # My profile (templates/accounts/profile.html)
    "profile": [(None, ["profile.css", "account-security.css", "appearance.css"])],
    # QA portal public pages (templates/qa_portal/public/base.html)
    "portal-public": [(None, ["qa-public.css", "vivid.css", "polish.css"])],
}


def bundle_filename(name):
    return f"nbte-{name}.bundle.css"


def source_files(name):
    """[(layer, filename)] that exist, in order."""
    out = []
    for layer, files in BUNDLES[name]:
        for f in files:
            optional = f.endswith("?")
            f = f.rstrip("?")
            if optional and not (CSS_DIR / f).exists():
                continue
            out.append((layer, f))
    return out


def build(name):
    """The bundle's text."""
    parts = [f"/* GENERATED by `python manage.py build_css` from core/css_bundles.py ({name}).\n"
             f"   Do not edit: edit the source files and rebuild. */\n"]
    if name == "core":
        parts.append(f"@layer {', '.join(LAYER_ORDER)};\n")
    for layer, f in source_files(name):
        text = (CSS_DIR / f).read_text(encoding="utf-8").strip("\n")
        if layer:
            # @property rules are hoisted out of the layer block (one line each).
            lines = text.split("\n")
            hoisted = [ln for ln in lines if ln.startswith("@property ")]
            if hoisted:
                parts.append("\n".join(hoisted) + "\n")
                text = "\n".join(ln for ln in lines if not ln.startswith("@property "))
        header = f"\n/* ==== {f} ==== */\n"
        if layer:
            parts.append(f"{header}@layer {layer} {{\n{text}\n}}\n")
        else:
            parts.append(f"{header}{text}\n")
    return "".join(parts)


def write_all():
    written = []
    for name in BUNDLES:
        path = CSS_DIR / bundle_filename(name)
        text = build(name)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            written.append(path.name)
    return written


def stale():
    return [bundle_filename(n) for n in BUNDLES
            if not (CSS_DIR / bundle_filename(n)).exists()
            or (CSS_DIR / bundle_filename(n)).read_text(encoding="utf-8") != build(n)]
