"""P.11: the access report — who can see which institution and why, counts
per role, under the current and the proposed privacy mode.

Names: only demo accounts are named; any other account is shown as
"(account #pk)" so the report can be shared.
"""
from __future__ import annotations

from collections import OrderedDict

DEMO_DOMAINS = ("@demo.nbte.local", "@demo.nbte.test", "@demo-poly.local", "@demo-health.local", "@p4demo.local")


def label(user):
    email = (user.email or "").lower()
    if email.endswith(DEMO_DOMAINS):
        return email
    return f"(account #{user.pk})"


def _count(ids, total):
    from .access import FULL
    return total if ids is FULL else len(ids)


def impact():
    """Per role: users, institutions visible (sum) in each mode, users losing all sight."""
    from accounts.models import User
    from institutions.models import Institution

    from . import access
    total = Institution.unscoped.count()
    rows = OrderedDict()
    for u in User.objects.filter(is_active=True, user_type="staff").select_related("role").order_by("pk"):
        code = u.role.code if u.role_id else "(no role)"
        r = rows.setdefault(code, {"users": 0, "department": 0, "assignment": 0, "lose_all": 0, "full_after": 0})
        r["users"] += 1
        with access.mode_override("department"):
            access.clear_request_cache(u)
            before = _count(access.visible_institution_ids(u), total)
        with access.mode_override("assignment"):
            access.clear_request_cache(u)
            vis = access.visible_institution_ids(u)
            after = _count(vis, total)
            if vis is access.FULL:
                r["full_after"] += 1
        access.clear_request_cache(u)
        r["department"] += before
        r["assignment"] += after
        if before and not after:
            r["lose_all"] += 1
    return total, rows


def impact_text():
    total, rows = impact()
    lines = [f"Institutions: {total}", "",
             "| Role | Staff | Visible now (department mode, sum) | Visible after (assignment mode, sum) | "
             "See everything after | Lose all sight |", "|---|---:|---:|---:|---:|---:|"]
    for code, r in rows.items():
        lines.append(f"| `{code}` | {r['users']} | {r['department']} | {r['assignment']} | {r['full_after']} | "
                     f"{r['lose_all']} |")
    return "\n".join(lines)


def full_report(mode="assignment"):
    from django.utils import timezone

    from institutions.models import Institution

    from . import access
    lines = ["# Need-to-know access report (P.11, X1–X4)", "",
             f"Run: {timezone.now():%Y-%m-%d %H:%M} · current `qa.privacy.mode`: **{access.privacy_mode()}** · "
             f"report computed for: **{mode}**", "",
             "Only demo accounts are named; other accounts appear as “(account #id)”. Generated by "
             "`python manage.py access_report --write`.", "", "## 1. Impact per role", "", impact_text(), "",
             "## 2. Who can see each institution and why", ""]
    with access.mode_override(mode):
        for inst in Institution.unscoped.order_by("name"):
            rows = access.who_can_see(inst, mode=mode)
            counts = OrderedDict()
            for r in rows:
                counts[r["level"]] = counts.get(r["level"], 0) + 1
            lines.append(f"### {inst.name} ({inst.code})")
            lines.append("")
            lines.append("Levels: " + ", ".join(f"{k} {v}" for k, v in counts.items()))
            lines.append("")
            lines.append("| Account | Level | Why |")
            lines.append("|---|---|---|")
            for r in sorted(rows, key=lambda r: (["full", "department", "own", "summary", "institution"]
                                                .index(r["level"]), r["user"].pk)):
                why = "; ".join(x["reason"] for x in r["reasons"])
                lines.append(f"| {label(r['user'])} | {r['level']} | {why} |")
            lines.append("")
    return "\n".join(lines)
